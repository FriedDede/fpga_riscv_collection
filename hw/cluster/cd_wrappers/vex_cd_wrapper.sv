// Description: VexRiscv (hw/cores/vex/VexRiscv) in its own clock domain. VexRiscvU55 is generated by the
//              Makefile in build/<run>/vexriscv/VexRiscvU55.v (hw/cores/vex/GenVexRiscvU55.scala:
//              GenFullNoMmuMaxPerf, reset vector 0x0, 64 bit cache memory interface). Its two AXI masters
//              (I$ refills, D$ refills/write-through/uncached accesses) are crossed to the cluster
//              domain with axi_cdc (upsized first if AxiDataWidth differs from the core one). The interrupts can come from any
//              domain and are synchronized here.
// Author: Andrea Motta
`include "axi_assign.svh"

module vex_cd_wrapper #(
    parameter int unsigned AxiAddrWidth = 32,   // VexRiscvU55: 32
    parameter int unsigned AxiDataWidth = 64,   // cluster side, VexRiscvU55: 64
    parameter int unsigned AxiUserWidth = 1,
    parameter int unsigned AxiIdWidth   = 1,    // VexRiscvU55: 1 (always 0)
    parameter int unsigned CdcLogDepth  = 2
)(
    // core domain
    input  logic        clk_core_i,
    // cluster domain
    input  logic        clk_cluster_i,
    input  logic        rst_cluster_ni,
    // asynchronous reset, released synchronously to clk_core_i inside
    input  logic        rst_ni,
    input  logic [31:0] hart_id_i,      // core index in the cluster
    // interrupts, any domain
    input  logic        timer_irq_i,    // mtip
    input  logic        soft_irq_i,     // msip
    input  logic        ext_irq_i,      // meip
    // cluster domain AXI masters
    AXI_BUS.Master      ibus,           // I$ refills (read only)
    AXI_BUS.Master      dbus            // D$ and uncached accesses
);

    localparam int unsigned VexDataWidth = 64;  // memDataWidth of GenVexRiscvU55.scala

// -----------------
// Reset and interrupts
// -----------------
    logic rst_core_n;
    rstgen i_rstgen_core (
        .clk_i        ( clk_core_i ),
        .rst_ni       ( rst_ni     ),
        .test_mode_i  ( 1'b0       ),
        .rst_no       ( rst_core_n ),
        .init_no      (            )
    );

    logic [2:0] irq_async, irq;
    assign irq_async = {ext_irq_i, soft_irq_i, timer_irq_i};
    for (genvar k = 0; k < 3; ++k) begin : gen_sync_irq
        sync i_sync_irq (.clk_i(clk_core_i), .rst_ni(rst_core_n), .serial_i(irq_async[k]), .serial_o(irq[k]));
    end

// -----------------
// Core
// -----------------
    // 0: ibus, 1: dbus
    AXI_BUS #(
        .AXI_ADDR_WIDTH ( AxiAddrWidth ),
        .AXI_DATA_WIDTH ( VexDataWidth ),
        .AXI_ID_WIDTH   ( AxiIdWidth   ),
        .AXI_USER_WIDTH ( AxiUserWidth )
    ) axi_vex[1:0]();

    // no atomics and user signals, the ibus is read only
    assign axi_vex[0].aw_valid  = 1'b0;
    assign axi_vex[0].aw_id     = '0;
    assign axi_vex[0].aw_addr   = '0;
    assign axi_vex[0].aw_len    = '0;
    assign axi_vex[0].aw_size   = '0;
    assign axi_vex[0].aw_burst  = '0;
    assign axi_vex[0].aw_lock   = '0;
    assign axi_vex[0].aw_cache  = '0;
    assign axi_vex[0].aw_prot   = '0;
    assign axi_vex[0].aw_qos    = '0;
    assign axi_vex[0].aw_region = '0;
    assign axi_vex[0].w_valid   = 1'b0;
    assign axi_vex[0].w_data    = '0;
    assign axi_vex[0].w_strb    = '0;
    assign axi_vex[0].w_last    = 1'b0;
    assign axi_vex[0].b_ready   = 1'b1;
    for (genvar k = 0; k < 2; ++k) begin : gen_tie
        assign axi_vex[k].aw_atop = '0;
        assign axi_vex[k].aw_user = '0;
        assign axi_vex[k].w_user  = '0;
        assign axi_vex[k].ar_user = '0;
    end

    // VexRiscv reset is active high
    VexRiscvU55 i_vex (
        .clk                       ( clk_core_i              ),
        .reset                     ( ~rst_core_n             ),
        .hartId                    ( hart_id_i               ),
        .timerInterrupt            ( irq[0]                  ),
        .softwareInterrupt         ( irq[1]                  ),
        .externalInterrupt         ( irq[2]                  ),
        // ibus
        .iBusAxi_ar_valid          ( axi_vex[0].ar_valid     ),
        .iBusAxi_ar_ready          ( axi_vex[0].ar_ready     ),
        .iBusAxi_ar_payload_addr   ( axi_vex[0].ar_addr      ),
        .iBusAxi_ar_payload_id     ( axi_vex[0].ar_id        ),
        .iBusAxi_ar_payload_region ( axi_vex[0].ar_region    ),
        .iBusAxi_ar_payload_len    ( axi_vex[0].ar_len       ),
        .iBusAxi_ar_payload_size   ( axi_vex[0].ar_size      ),
        .iBusAxi_ar_payload_burst  ( axi_vex[0].ar_burst     ),
        .iBusAxi_ar_payload_lock   ( axi_vex[0].ar_lock      ),
        .iBusAxi_ar_payload_cache  ( axi_vex[0].ar_cache     ),
        .iBusAxi_ar_payload_qos    ( axi_vex[0].ar_qos       ),
        .iBusAxi_ar_payload_prot   ( axi_vex[0].ar_prot      ),
        .iBusAxi_r_valid           ( axi_vex[0].r_valid      ),
        .iBusAxi_r_ready           ( axi_vex[0].r_ready      ),
        .iBusAxi_r_payload_data    ( axi_vex[0].r_data       ),
        .iBusAxi_r_payload_id      ( axi_vex[0].r_id         ),
        .iBusAxi_r_payload_resp    ( axi_vex[0].r_resp       ),
        .iBusAxi_r_payload_last    ( axi_vex[0].r_last       ),
        // dbus
        .dBusAxi_aw_valid          ( axi_vex[1].aw_valid     ),
        .dBusAxi_aw_ready          ( axi_vex[1].aw_ready     ),
        .dBusAxi_aw_payload_addr   ( axi_vex[1].aw_addr      ),
        .dBusAxi_aw_payload_id     ( axi_vex[1].aw_id        ),
        .dBusAxi_aw_payload_region ( axi_vex[1].aw_region    ),
        .dBusAxi_aw_payload_len    ( axi_vex[1].aw_len       ),
        .dBusAxi_aw_payload_size   ( axi_vex[1].aw_size      ),
        .dBusAxi_aw_payload_burst  ( axi_vex[1].aw_burst     ),
        .dBusAxi_aw_payload_lock   ( axi_vex[1].aw_lock      ),
        .dBusAxi_aw_payload_cache  ( axi_vex[1].aw_cache     ),
        .dBusAxi_aw_payload_qos    ( axi_vex[1].aw_qos       ),
        .dBusAxi_aw_payload_prot   ( axi_vex[1].aw_prot      ),
        .dBusAxi_w_valid           ( axi_vex[1].w_valid      ),
        .dBusAxi_w_ready           ( axi_vex[1].w_ready      ),
        .dBusAxi_w_payload_data    ( axi_vex[1].w_data       ),
        .dBusAxi_w_payload_strb    ( axi_vex[1].w_strb       ),
        .dBusAxi_w_payload_last    ( axi_vex[1].w_last       ),
        .dBusAxi_b_valid           ( axi_vex[1].b_valid      ),
        .dBusAxi_b_ready           ( axi_vex[1].b_ready      ),
        .dBusAxi_b_payload_id      ( axi_vex[1].b_id         ),
        .dBusAxi_b_payload_resp    ( axi_vex[1].b_resp       ),
        .dBusAxi_ar_valid          ( axi_vex[1].ar_valid     ),
        .dBusAxi_ar_ready          ( axi_vex[1].ar_ready     ),
        .dBusAxi_ar_payload_addr   ( axi_vex[1].ar_addr      ),
        .dBusAxi_ar_payload_id     ( axi_vex[1].ar_id        ),
        .dBusAxi_ar_payload_region ( axi_vex[1].ar_region    ),
        .dBusAxi_ar_payload_len    ( axi_vex[1].ar_len       ),
        .dBusAxi_ar_payload_size   ( axi_vex[1].ar_size      ),
        .dBusAxi_ar_payload_burst  ( axi_vex[1].ar_burst     ),
        .dBusAxi_ar_payload_lock   ( axi_vex[1].ar_lock      ),
        .dBusAxi_ar_payload_cache  ( axi_vex[1].ar_cache     ),
        .dBusAxi_ar_payload_qos    ( axi_vex[1].ar_qos       ),
        .dBusAxi_ar_payload_prot   ( axi_vex[1].ar_prot      ),
        .dBusAxi_r_valid           ( axi_vex[1].r_valid      ),
        .dBusAxi_r_ready           ( axi_vex[1].r_ready      ),
        .dBusAxi_r_payload_data    ( axi_vex[1].r_data       ),
        .dBusAxi_r_payload_id      ( axi_vex[1].r_id         ),
        .dBusAxi_r_payload_resp    ( axi_vex[1].r_resp       ),
        .dBusAxi_r_payload_last    ( axi_vex[1].r_last       )
    );

// -----------------
// Data width conversion and clock domain crossings
// -----------------
    AXI_BUS #(
        .AXI_ADDR_WIDTH ( AxiAddrWidth ),
        .AXI_DATA_WIDTH ( AxiDataWidth ),
        .AXI_ID_WIDTH   ( AxiIdWidth   ),
        .AXI_USER_WIDTH ( AxiUserWidth )
    ) axi_core[1:0](), axi_cluster[1:0]();

    for (genvar k = 0; k < 2; ++k) begin : gen_cdc
        if (AxiDataWidth != VexDataWidth) begin : gen_dw
            axi_dw_converter_intf #(
                .AXI_ID_WIDTH            ( AxiIdWidth   ),
                .AXI_ADDR_WIDTH          ( AxiAddrWidth ),
                .AXI_SLV_PORT_DATA_WIDTH ( VexDataWidth ),
                .AXI_MST_PORT_DATA_WIDTH ( AxiDataWidth ),
                .AXI_USER_WIDTH          ( AxiUserWidth ),
                .AXI_MAX_READS           ( 2            )
            ) i_dw (
                .clk_i  ( clk_core_i  ),
                .rst_ni ( rst_core_n  ),
                .slv    ( axi_vex[k]  ),
                .mst    ( axi_core[k] )
            );
        end else begin : gen_no_dw
            `AXI_ASSIGN(axi_core[k], axi_vex[k])
        end

        axi_cdc_intf #(
            .AXI_ID_WIDTH   ( AxiIdWidth   ),
            .AXI_ADDR_WIDTH ( AxiAddrWidth ),
            .AXI_DATA_WIDTH ( AxiDataWidth ),
            .AXI_USER_WIDTH ( AxiUserWidth ),
            .LOG_DEPTH      ( CdcLogDepth  )
        ) i_cdc (
            .src_clk_i  ( clk_core_i     ),
            .src_rst_ni ( rst_core_n     ),
            .src        ( axi_core[k]    ),
            .dst_clk_i  ( clk_cluster_i  ),
            .dst_rst_ni ( rst_cluster_ni ),
            .dst        ( axi_cluster[k] )
        );
    end

    `AXI_ASSIGN(ibus, axi_cluster[0])
    `AXI_ASSIGN(dbus, axi_cluster[1])

endmodule
