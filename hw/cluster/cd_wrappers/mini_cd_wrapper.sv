// Description: riscv-mini (ucb-bar, hw/cores/riscv-mini) Tile in its own clock domain.
//              Tile is generated by the Makefile in build/<run>/riscv_mini/Tile.sv. RV32I, reset pc
//              0x200, machine mode trap vector 0x1c0, no external interrupts, write-back I$ and D$ on one
//              AXI master (crossed to the cluster domain with axi_cdc). The host interface
//              (mtohost / mfromhost csrs) is not connected.
// Author: Andrea Motta
`include "axi_assign.svh"

module mini_cd_wrapper #(
    parameter int unsigned AxiAddrWidth = 32,   // Tile: 32
    parameter int unsigned AxiDataWidth = 64,   // Tile: 64
    parameter int unsigned AxiUserWidth = 1,
    parameter int unsigned AxiIdWidth   = 5,    // Tile: 5
    parameter int unsigned CdcLogDepth  = 2
)(
    // core domain
    input  logic        clk_core_i,
    // cluster domain
    input  logic        clk_cluster_i,
    input  logic        rst_cluster_ni,
    // asynchronous reset, released synchronously to clk_core_i inside
    input  logic        rst_ni,
    // cluster domain AXI master
    AXI_BUS.Master      noc
);

// -----------------
// Reset
// -----------------
    logic rst_core_n;
    rstgen i_rstgen_core (
        .clk_i        ( clk_core_i ),
        .rst_ni       ( rst_ni     ),
        .test_mode_i  ( 1'b0       ),
        .rst_no       ( rst_core_n ),
        .init_no      (            )
    );

// -----------------
// Core
// -----------------
    AXI_BUS #(
        .AXI_ADDR_WIDTH ( AxiAddrWidth ),
        .AXI_DATA_WIDTH ( AxiDataWidth ),
        .AXI_ID_WIDTH   ( AxiIdWidth   ),
        .AXI_USER_WIDTH ( AxiUserWidth )
    ) axi_core();

    // no region, atomics and user signals on riscv-mini
    assign axi_core.aw_region = '0;
    assign axi_core.aw_atop   = '0;
    assign axi_core.aw_user   = '0;
    assign axi_core.w_user    = '0;
    assign axi_core.ar_region = '0;
    assign axi_core.ar_user   = '0;

    // Tile reset is synchronous active high
    Tile i_tile (
        .clock                  ( clk_core_i              ),
        .reset                  ( ~rst_core_n             ),
        .io_host_fromhost_valid ( 1'b0                    ),
        .io_host_fromhost_bits  ( '0                      ),
        .io_host_tohost         (                         ),
        .io_nasti_aw_ready      ( axi_core.aw_ready       ),
        .io_nasti_aw_valid      ( axi_core.aw_valid       ),
        .io_nasti_aw_bits_id    ( axi_core.aw_id          ),
        .io_nasti_aw_bits_addr  ( axi_core.aw_addr        ),
        .io_nasti_aw_bits_len   ( axi_core.aw_len         ),
        .io_nasti_aw_bits_size  ( axi_core.aw_size        ),
        .io_nasti_aw_bits_burst ( axi_core.aw_burst       ),
        .io_nasti_aw_bits_lock  ( axi_core.aw_lock        ),
        .io_nasti_aw_bits_cache ( axi_core.aw_cache       ),
        .io_nasti_aw_bits_prot  ( axi_core.aw_prot        ),
        .io_nasti_aw_bits_qos   ( axi_core.aw_qos         ),
        .io_nasti_w_ready       ( axi_core.w_ready        ),
        .io_nasti_w_valid       ( axi_core.w_valid        ),
        .io_nasti_w_bits_data   ( axi_core.w_data         ),
        .io_nasti_w_bits_strb   ( axi_core.w_strb         ),
        .io_nasti_w_bits_last   ( axi_core.w_last         ),
        .io_nasti_b_ready       ( axi_core.b_ready        ),
        .io_nasti_b_valid       ( axi_core.b_valid        ),
        .io_nasti_b_bits_id     ( axi_core.b_id           ),
        .io_nasti_b_bits_resp   ( axi_core.b_resp         ),
        .io_nasti_ar_ready      ( axi_core.ar_ready       ),
        .io_nasti_ar_valid      ( axi_core.ar_valid       ),
        .io_nasti_ar_bits_id    ( axi_core.ar_id          ),
        .io_nasti_ar_bits_addr  ( axi_core.ar_addr        ),
        .io_nasti_ar_bits_len   ( axi_core.ar_len         ),
        .io_nasti_ar_bits_size  ( axi_core.ar_size        ),
        .io_nasti_ar_bits_burst ( axi_core.ar_burst       ),
        .io_nasti_ar_bits_lock  ( axi_core.ar_lock        ),
        .io_nasti_ar_bits_cache ( axi_core.ar_cache       ),
        .io_nasti_ar_bits_prot  ( axi_core.ar_prot        ),
        .io_nasti_ar_bits_qos   ( axi_core.ar_qos         ),
        .io_nasti_r_ready       ( axi_core.r_ready        ),
        .io_nasti_r_valid       ( axi_core.r_valid        ),
        .io_nasti_r_bits_id     ( axi_core.r_id           ),
        .io_nasti_r_bits_data   ( axi_core.r_data         ),
        .io_nasti_r_bits_resp   ( axi_core.r_resp         ),
        .io_nasti_r_bits_last   ( axi_core.r_last         )
    );

// -----------------
// Clock domain crossing
// -----------------
    axi_cdc_intf #(
        .AXI_ID_WIDTH   ( AxiIdWidth   ),
        .AXI_ADDR_WIDTH ( AxiAddrWidth ),
        .AXI_DATA_WIDTH ( AxiDataWidth ),
        .AXI_USER_WIDTH ( AxiUserWidth ),
        .LOG_DEPTH      ( CdcLogDepth  )
    ) i_cdc (
        .src_clk_i  ( clk_core_i     ),
        .src_rst_ni ( rst_core_n     ),
        .src        ( axi_core       ),
        .dst_clk_i  ( clk_cluster_i  ),
        .dst_rst_ni ( rst_cluster_ni ),
        .dst        ( noc            )
    );

endmodule
